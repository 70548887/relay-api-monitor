import { test, expect } from '@playwright/test';
test('isolated artifact preview executes scripts inside an opaque sandbox',async({page})=>{
  const id='browser-sandbox-fixture';
  const code='<!doctype html><html><body><svg xmlns="http://www.w3.org/2000/svg" width="1440" height="900"><rect width="1440" height="900" fill="#edf5e3"/></svg><script>function relayPreview(){document.body.dataset.relayPreview="ready";try{window.parent.document.body.dataset.leaked="yes";document.body.dataset.parentAccess="allowed"}catch{document.body.dataset.parentAccess="blocked"}try{void document.cookie;document.body.dataset.cookieAccess="allowed"}catch{document.body.dataset.cookieAccess="blocked"}}relayPreview();</script></body></html>';
  const artifact={id,job_id:'fixture-job',model_id:'fixture-model',channel_id:'fixture-group',template_id:'cn_html',template_version:1,prompt:'sandbox fixture prompt',requested_model:'sandbox fixture',returned_model:'fixture',protocol:'chat',kind:'html',code,preview_document:code,reasoning_effort:'',thinking_mode:'',thinking_budget:0,usage:{input_tokens:1,output_tokens:2,total_tokens:3},first_text_ms:1,duration_ms:100,created_at:'2026-10-26T00:00:00Z',started_at:'2026-10-26T00:00:00Z',group_verification_status:'unsupported',verified_group:''};
  const group={id:'fixture-group',channel_id:'fixture-group',channel_name:'Sandbox fixture group',platform_id:'fixture-platform',platform_name:'Sandbox fixture platform',model_id:'fixture-model',requested_model:'sandbox fixture',models:[],group_verification:{status:'unsupported',scope:'token_binding'},reasoning_effort:'',thinking_mode:'',thinking_budget:0,automatic_enabled:false,interval_seconds:600,next_run_at:null,latest_attempt:null,history:[artifact]};
  await page.route('**/api/v1/public/templates',route=>route.fulfill({json:[{id:'cn_html',prompt:'sandbox fixture prompt',version:1}]}));
  await page.route('**/api/v1/public/intelligence?**',route=>route.fulfill({json:{groups:[group],history_scope:'group',updated_at:'2026-10-26T00:00:00Z',worker_online:true}}));
  await page.route(`**/api/v1/public/artifacts/${id}`,route=>route.fulfill({json:artifact}));
  await page.goto('/intelligence');
  await page.getByRole('group',{name:'平台',exact:true}).getByRole('button',{name:group.platform_name,exact:true}).click();
  await page.getByRole('group',{name:'分组',exact:true}).getByRole('button',{name:group.channel_name,exact:true}).click();
  const card=page.locator(`[data-artifact-id="${id}"]`);
  await expect(card).toBeVisible();
  await card.getByRole('button',{name:/预览/}).click();
  const work=page.locator('.intelligence-work');
  const element=work.locator('iframe');
  await expect(element).toHaveAttribute('sandbox','allow-scripts');
  await expect(element).toHaveAttribute('referrerpolicy','no-referrer');
  const frame=element.contentFrame();
  await expect(frame.locator('body')).toHaveAttribute('data-relay-preview','ready');
  await expect(frame.locator('body')).toHaveAttribute('data-parent-access','blocked');
  await expect(frame.locator('body')).toHaveAttribute('data-cookie-access','blocked');
  expect(await frame.locator('body').evaluate(()=>{try{void window.parent.document;return false}catch{return true}})).toBe(true);
  expect(await page.locator('body').getAttribute('data-leaked')).toBeNull();
  await work.getByText('源码',{exact:true}).click();
  await expect(work.locator('iframe')).toHaveCount(0);
  await expect(work.locator('pre')).toContainText('relayPreview');
  const downloading=page.waitForEvent('download');
  await work.getByRole('button',{name:/下\s*载$/}).click();
  const downloaded=await downloading;
  expect(downloaded.suggestedFilename()).toMatch(/\.html$/);
  const stream=await downloaded.createReadStream();
  let source='';
  if(stream)for await(const chunk of stream)source+=chunk.toString();
  expect(source).toContain('relayPreview');
  await page.setViewportSize({width:390,height:844});
  await expect(work.locator('pre')).toBeVisible();
  const size=await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
  expect(size.scroll).toBeLessThanOrEqual(size.width);
});
