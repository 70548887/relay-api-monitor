import { test, expect, type Page } from '@playwright/test';
const base = new URL(process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:42783');
const isolated = process.env.PLAYWRIGHT_ADMIN_TESTS === '1' && ['127.0.0.1','localhost'].includes(base.hostname) && !['42783','42784','8080','5173',''].includes(base.port);
test('isolated administrator setup, CRUD, queue cancellation and password change', async ({ page }) => {
  test.skip(!isolated, 'Explicit opt-in and a separate local server/data directory are required.');
  const username='e2e-admin';
  const password=process.env.PLAYWRIGHT_ADMIN_PASSWORD||'Relay_E2E_Only_2026';
  const updatedPassword='Relay_E2E_Updated_2026';
  const suffix=Date.now().toString(36);
  const platform=`E2E 临时平台 ${suffix}`;
  const channel=`E2E 临时分组 ${suffix}`;
  const model=`E2E 临时模型 ${suffix}`;
  const status=await page.request.get('/api/v1/setup/status');
  const initialized=(await status.json()).initialized as boolean;
  await page.goto('/admin');
  await page.getByLabel('用户名',{exact:true}).fill(username);
  await page.getByLabel('密码',{exact:true}).fill(password);
  if(!initialized)await page.getByLabel('确认密码',{exact:true}).fill(password);
  await page.getByRole('button',{name:initialized?'登录工作台':'创建管理员并登录',exact:true}).click();
  await expect(page.getByRole('heading',{name:'工作台',exact:true})).toBeVisible();

  await page.getByRole('link',{name:/平台与分组$/}).click();
  await page.getByRole('button',{name:/新增平台$/}).click();
  await page.getByLabel('平台名称',{exact:true}).fill(platform);
  await page.getByLabel('描述',{exact:true}).fill('Isolated browser test only');
  await confirmModal(page);
  await expect(page.getByRole('row').filter({hasText:platform})).toBeVisible();
  await page.getByRole('tab',{name:/分组 \(\d+\)/}).click();
  await page.getByRole('button',{name:/新增分组$/}).click();
  await choose(page,'所属平台',platform);
  await page.getByLabel('分组名称',{exact:true}).fill(channel);
  await page.getByLabel('接口地址',{exact:true}).fill('https://example.com/v1');
  await page.getByLabel('API Key',{exact:true}).fill('e2e-placeholder-key-not-real');
  await confirmModal(page);
  await expect(page.getByRole('row').filter({hasText:channel})).toBeVisible();

  await page.getByRole('link',{name:/模型配置$/}).click();
  await page.getByRole('button',{name:/手动添加模型$/}).click();
  await choose(page,'所属分组',channel);
  await page.getByLabel('上游模型 ID',{exact:true}).fill('e2e-placeholder-model');
  await page.getByLabel('显示名称',{exact:true}).fill(model);
  await expect(page.getByLabel('周期健康检测',{exact:true})).not.toBeChecked();
  await expect(page.getByText('保存后预计每日自动请求约 0 次',{exact:true})).toBeVisible();
  await confirmModal(page);
  const modelRow=page.getByRole('row').filter({hasText:model});
  await expect(modelRow).toBeVisible();
  await modelRow.getByRole('button',{name:/编\s*辑$/}).click();
  await expect(page.getByLabel('上游模型 ID',{exact:true})).toBeDisabled();
  await page.getByLabel('显示名称',{exact:true}).fill(`${model} · 已编辑`);
  await confirmModal(page);
  await expect(modelRow).toContainText('已编辑');
  await modelRow.getByRole('button',{name:/检\s*测$/}).click();
  await page.getByRole('link',{name:/任务与作品$/}).click();
  const queuedRow=page.getByRole('row').filter({hasText:'排队中'}).first();
  await expect(queuedRow).toBeVisible();
  const jobRowKey=await queuedRow.getAttribute('data-row-key');
  await queuedRow.getByRole('button',{name:'取消任务',exact:true}).click();
  await page.getByRole('button',{name:/确\s*定$/}).click();
  await expect(page.locator(`tr[data-row-key="${jobRowKey}"]`)).toContainText('已取消');

  await page.getByRole('link',{name:/系统设置$/}).click();
  await page.getByLabel('检测数据保留（天）',{exact:true}).fill('31');
  await page.getByRole('button',{name:'保存设置',exact:true}).click();
  await page.reload();
  await expect(page.getByLabel('检测数据保留（天）',{exact:true})).toHaveValue('31');
  await page.getByLabel('当前密码',{exact:true}).fill(password);
  await page.getByLabel('新密码',{exact:true}).fill(updatedPassword);
  await page.getByLabel('确认新密码',{exact:true}).fill(updatedPassword);
  await page.getByRole('button',{name:'更新密码',exact:true}).click();
  await expect(page.getByRole('heading',{name:'欢迎回来',exact:true})).toBeVisible();
  await page.getByLabel('用户名',{exact:true}).fill(username);
  await page.getByLabel('密码',{exact:true}).fill(updatedPassword);
  await page.getByRole('button',{name:'登录工作台',exact:true}).click();
  await expect(page.getByRole('heading',{name:'按你的节奏，持续观测。',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'退出登录',exact:true}).click();
  await expect(page.getByRole('heading',{name:'欢迎回来',exact:true})).toBeVisible();
});
async function choose(page:Page,label:string,text:string){await page.getByLabel(label,{exact:true}).click();await page.getByTitle(text,{exact:true}).click()}
async function confirmModal(page:Page){const dialog=page.getByRole('dialog');await dialog.getByRole('button',{name:/确\s*定$/}).click();await expect(dialog).not.toBeVisible()}
